package pw.binom.db.kpostgresql.orm

import kotlinx.coroutines.test.runTest
import kotlinx.serialization.Serializable
import pw.binom.db.orm.AutoGenerated
import pw.binom.db.orm.ColumnName
import pw.binom.db.orm.Embedded
import pw.binom.db.orm.EmbeddedPrefix
import pw.binom.db.orm.Id
import pw.binom.db.orm.TableName
import pw.binom.db.kpostgresql.PostgresConfig
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNotNull
import kotlin.test.assertNull
import kotlin.test.assertTrue

/**
 * Сквозной тест ORM на живой базе.
 *
 * ## Почему не Testcontainers
 *
 * В LXC 183 Testcontainers не работают: нет Docker-демона и вложенной
 * виртуализации. Тест ходит в Postgres, поднятый на той же машине, и берёт
 * параметры из переменных окружения. Если переменных нет — тест
 * пропускается, а не падает: обычный `./gradlew test` не должен требовать
 * базы.
 *
 * ## Что проверяется
 *
 * Не «работает ли SQL», а стыки, где ошибки тихие:
 *
 * * `:name` → `$N` — если конвертер переставит аргументы, значения лягут не
 *   в те колонки, и запрос не упадёт, а вернёт неверные данные;
 * * `@ColumnName` — поле `email`, колонка `email_addr`: путаница даст
 *   `null` вместо значения;
 * * `@Embedded` — путь `home_.city` должен превратиться в колонку `home_city`;
 * * `@AutoGenerated` — `BIGSERIAL` должен выдать ключ, а не `0`.
 */
class PgOrmLiveTest {

    private val host = System.getenv("PG_HOST") ?: "192.168.76.251"
    private val port = System.getenv("PG_PORT")?.toInt() ?: 5432
    private val db = System.getenv("PG_DB") ?: "console"
    private val user = System.getenv("PG_USER") ?: "console"
    private val password = System.getenv("PG_PASSWORD") ?: ""

    private fun config() = PostgresConfig(
        host = host,
        port = port,
        database = db,
        user = user,
        password = password,
    )

    @Test
    fun `полный круг CRUD на живой базе`() = runTest {
        if (password.isEmpty()) {
            println("PG_PASSWORD не задан — тест пропущен")
            return@runTest
        }

        PgOrm.connect(config(), poolSize = 2).use { pg ->
            pg.transaction { orm ->
                // Схема создаётся идемпотентно, но таблицу лучше начать с нуля:
                // иначе остатки прошлого прогона исказят счётчики.
                orm.createSchema(LiveUser.serializer(), LiveOrder.serializer(), LivePerson.serializer())
                orm.deleteAll(LiveUser.serializer())
                orm.deleteAll(LiveOrder.serializer())
                orm.deleteAll(LivePerson.serializer())

                // --- INSERT с авто-ключом ---
                orm.insert(LiveUser.serializer(), LiveUser(name = "Анна", email = "anna@example.com"))
                orm.insert(LiveUser.serializer(), LiveUser(name = "Борис", email = "boris@example.com"))

                val all = orm.findAll(LiveUser.serializer())
                assertEquals(2, all.size, "должно быть две строки")

                val anna = all.first { it.name == "Анна" }
                assertTrue(anna.id > 0, "BIGSERIAL должен выдать ключ, получено ${anna.id}")
                // Главная проверка: @ColumnName("email_addr") и поле email.
                assertEquals("anna@example.com", anna.email, "@ColumnName не сработал")

                // --- findById ---
                val found = orm.findById(LiveUser.serializer(), anna.id)
                assertNotNull(found)
                assertEquals("Анна", found.name)

                // --- UPDATE ---
                orm.update(LiveUser.serializer(), anna.copy(name = "Анна П.", score = 42))
                val updated = orm.findById(LiveUser.serializer(), anna.id)
                assertNotNull(updated)
                assertEquals("Анна П.", updated.name)
                assertEquals(42, updated.score)

                // --- UPSERT: обновляет существующую ---
                orm.upsert(LiveUser.serializer(), anna.copy(name = "Анна У.", score = 7))
                val upserted = orm.findById(LiveUser.serializer(), anna.id)
                assertNotNull(upserted)
                assertEquals("Анна У.", upserted.name)
                assertEquals(2, orm.findAll(LiveUser.serializer()).size, "upsert не должен плодить строки")

                // --- @Embedded ---
                orm.insert(
                    LivePerson.serializer(),
                    LivePerson(id = 1, name = "Иван", address = LiveAddress("Москва", "Тверская")),
                )
                val person = orm.findById(LivePerson.serializer(), 1L)
                assertNotNull(person)
                assertEquals("Москва", person.address.city, "@Embedded: город не прочитан")
                assertEquals("Тверская", person.address.street, "@Embedded: улица не прочитана")

                // --- UPDATE по неуникальному полю через ручной SQL ---
                val byName = orm.select(
                    "SELECT id, name, email_addr, active, score FROM live_users WHERE name = :n",
                    LiveUser.serializer(),
                    "n" to "Анна У.",
                )
                assertEquals(1, byName.size, "ручной SELECT с параметром не нашёл строку")
                assertEquals(7, byName[0].score)

                // --- DELETE ---
                orm.deleteById(LiveUser.serializer(), anna.id)
                assertNull(orm.findById(LiveUser.serializer(), anna.id), "строка должна быть удалена")
                assertEquals(1, orm.findAll(LiveUser.serializer()).size)

                // Откат: транзакция завершится исключением, но тест не должен
                // оставить мусор. Убираем за собой.
                orm.deleteAll(LiveUser.serializer())
                orm.deleteAll(LivePerson.serializer())
            }
        }
    }

    @Test
    fun `createSchema идемпотентен`() = runTest {
        if (password.isEmpty()) return@runTest

        PgOrm.connect(config(), poolSize = 1, pingQuery = "SELECT 1").use { pg ->
            pg.read { orm ->
                // Дважды подряд — второй раз не должен падать на существующей таблице.
                orm.createSchema(LiveUser.serializer())
                orm.createSchema(LiveUser.serializer())
            }
        }
    }

    @Test
    fun `вложенный захват не блокирует пул на одном соединении`() = runTest {
        if (password.isEmpty()) return@runTest

        // Главная проверка пула: poolSize = 1 и запросы внутри транзакции.
        // Если бы Orm брал новое соединение на каждый вызов, здесь был бы
        // deadlock на 15 секунд — ровно то, что случилось при первом прогоне.
        PgOrm.connect(config(), poolSize = 1).use { pg ->
            pg.transaction { orm ->
                orm.createSchema(LiveUser.serializer())
                orm.deleteAll(LiveUser.serializer())
                orm.insert(LiveUser.serializer(), LiveUser(name = "Один", email = "one@example.com"))
                assertEquals(1, orm.findAll(LiveUser.serializer()).size)
                orm.deleteAll(LiveUser.serializer())
            }
        }
    }
}

@Serializable
@TableName("live_users")
data class LiveUser(
    @Id
    @AutoGenerated
    val id: Long = 0,
    val name: String,
    @ColumnName("email_addr")
    val email: String = "",
    val active: Boolean = true,
    val score: Int = 0,
)

@Serializable
@TableName("live_orders")
data class LiveOrder(
    @Id
    val id: Long,
    @ColumnName("user_id")
    val userId: Long,
    val amount: Double,
)

@Serializable
data class LiveAddress(
    val city: String,
    val street: String,
)

@Serializable
@TableName("live_people")
data class LivePerson(
    @Id
    val id: Long,
    val name: String,
    @Embedded
    @EmbeddedPrefix("home_")
    val address: LiveAddress,
)
